const ANGLE_LABEL: Record<CrossAngleKey, string> = { R: 'Right Angle Cross of', L: 'Left Angle Cross of', J: 'Juxtaposition Cross of' };

const INDEX = new Map<string, CrossRow>(ROWS.map((r) => [`${r[0]}${r[1]}`, r]));

/** Cari cross. Mengembalikan null bila tidak ada, atau gate Design Sun tabel ≠ hasil hitung. */
export function lookupIncarnationCross(
  angle: CrossAngleKey,
  personalitySun: number,
  designSun: number
): { name: string; designSun: number } | null {
  const row = INDEX.get(`${angle}${personalitySun}`);
  if (!row || row[2] !== designSun) return null;
  return { name: `${ANGLE_LABEL[angle]} ${row[3]}${row[4] ? ` ${row[4]}` : ''}`, designSun: row[2] };
}
